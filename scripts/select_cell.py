#!/usr/bin/env python
"""
Choose gamma and n_warmup for each UQ arm from TUNING runs, on validation data only
(DECISIONS D21; ERRATA E7 is what this avoids). Test Dice is never read.

  python scripts/select_cell.py --root results/multiclass_tune_v1 --dataset papila3 \
      --template configs/multiclass/final_template.yaml --out configs/multiclass/final.yaml

Rule (fixed in D21 before any tuning run):
  for every tuning run, simulate early stopping on validation mean soft Dice
  (patience 5) and take the validation Dice at the selected epoch;
  per cell (arm, gamma, n_warmup) average over the tuning seeds;
  per arm pick the cell with the highest mean; ties -> smaller gamma, then smaller n_warmup.
Writes the final manifest = template + {baseline, the chosen cell of each arm}.
"""

import argparse
import glob
import importlib.util
import os
import re

import pandas as pd
import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("select_offline", os.path.join(HERE, "select_offline.py"))
so = importlib.util.module_from_spec(spec)
spec.loader.exec_module(so)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--dataset", required=True)
    ap.add_argument("--backbone_dir", default="medsam")
    ap.add_argument("--loss_dir", default="weighted_ce")
    ap.add_argument("--patience", type=int, default=5)
    ap.add_argument("--template")
    ap.add_argument("--out")
    args = ap.parse_args()

    base = os.path.join(args.root, args.dataset, args.backbone_dir, args.loss_dir)
    rows = []
    for rd in glob.glob(os.path.join(base, "gamma_*", "n_warmup_*", "*", "run_*")):
        f = os.path.join(rd, "epoch_log.csv")
        if not os.path.exists(os.path.join(rd, "test_metrics.txt")) or not os.path.exists(f):
            continue
        g, w, arm, run = re.search(r"gamma_([^/]+)/n_warmup_([^/]+)/([^/]+)/run_(\d+)",
                                   rd.replace(os.sep, "/")).groups()
        ep = pd.read_csv(f)
        be, _ = so.simulate(ep, "val_soft_dice", -1, args.patience)
        rows.append({"arm": arm, "gamma": float(g), "n_warmup": int(w), "run": int(run),
                     "val_dice": float(ep.loc[ep.epoch == be, "val_soft_dice"].iloc[0]),
                     "best_epoch": be})
    if not rows:
        raise SystemExit(f"no finished tuning runs under {base}")
    df = pd.DataFrame(rows)
    cells = (df.groupby(["arm", "gamma", "n_warmup"])
               .agg(n=("val_dice", "size"), mean_val_dice=("val_dice", "mean"),
                    sd=("val_dice", "std"), mean_epoch=("best_epoch", "mean"))
               .reset_index())
    print(cells.sort_values(["arm", "mean_val_dice"], ascending=[True, False]).to_string(index=False))

    chosen = []
    for arm, c in cells.groupby("arm"):
        c = c.sort_values(["mean_val_dice", "gamma", "n_warmup"], ascending=[False, True, True])
        top = c.iloc[0]
        print(f"\n[{arm}] chosen: gamma={top.gamma:g} n_warmup={int(top.n_warmup)} "
              f"(mean val Dice {top.mean_val_dice:.4f}, n={int(top.n)})")
        chosen.append((arm, top))

    if args.template and args.out:
        man = yaml.safe_load(open(args.template))
        arms = [{"uq_type": "none"}]
        for arm, top in chosen:
            a = {"gamma": float(top.gamma), "n_warmup": int(top.n_warmup)}
            if arm.startswith("conformal_lac_"):
                a = {"uq_type": "conformal", "alpha": int(arm.split("_")[-1]) / 100, **a}
            else:
                a = {"uq_type": arm, **a}
            arms.append(a)
        man["arms"] = {args.dataset: arms}
        with open(args.out, "w") as f:
            f.write("# GENERATED by scripts/select_cell.py from validation-only tuning (D21). Do not edit.\n")
            yaml.safe_dump(man, f, sort_keys=False)
        print(f"\nwrote {args.out}")


if __name__ == "__main__":
    main()
